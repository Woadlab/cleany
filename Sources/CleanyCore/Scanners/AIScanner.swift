import Foundation

/// Discovers caches, telemetry, logs, stale binaries, and local LLM weights from AI developer tools.
public struct AIScanner: JunkScanner {
    public let category: JunkCategory = .aiClutter

    public init() {}

    public func scan(onProgress: @Sendable @escaping (ScanProgress) -> Void) async -> [JunkItem] {
        let home = FileManager.default.homeDirectoryForCurrentUser
        var items: [JunkItem] = []
        var totalBytes: UInt64 = 0

        struct Target {
            let relativePath: String
            let toolName: String
            let subcategory: String
            let description: String
        }

        let targets: [Target] = [
            // Claude Code / Anthropic
            Target(
                relativePath: ".claude/shell-snapshots",
                toolName: "Claude Code",
                subcategory: "Shell Snapshots",
                description: "Terminal command and execution snapshot history recorded by Claude Code CLI."
            ),
            Target(
                relativePath: ".claude/telemetry",
                toolName: "Claude Code",
                subcategory: "Telemetry Cache",
                description: "Cached telemetry events waiting to be sent or retained locally."
            ),
            Target(
                relativePath: ".claude/stats-cache.json",
                toolName: "Claude Code",
                subcategory: "Stats Cache",
                description: "Cached tool usage counters and CLI stats."
            ),
            Target(
                relativePath: ".local/share/claude/versions",
                toolName: "Claude Code",
                subcategory: "Stale Versions",
                description: "Previous versions of Claude CLI preserved after automatic updates."
            ),
            Target(
                relativePath: "Library/Logs/Claude",
                toolName: "Claude",
                subcategory: "Logs",
                description: "Diagnostic and debug log files generated by Claude Desktop."
            ),

            // Cursor Agent & Editor
            Target(
                relativePath: ".local/share/cursor-agent",
                toolName: "Cursor",
                subcategory: "Agent Logs & Caches",
                description: "Background agent logs, temporary indexing files, and model runtime caches."
            ),
            Target(
                relativePath: "Library/Application Support/Cursor/Cache",
                toolName: "Cursor",
                subcategory: "Web Cache",
                description: "GPU and web view caches from the Cursor IDE."
            ),
            Target(
                relativePath: "Library/Application Support/Cursor/Code Cache",
                toolName: "Cursor",
                subcategory: "V8 Code Cache",
                description: "Compiled JavaScript bytecode caches for Cursor editor plugins."
            ),

            // OpenCode
            Target(
                relativePath: ".local/share/opencode/log",
                toolName: "OpenCode",
                subcategory: "Logs",
                description: "Runtime and tool execution logs from OpenCode."
            ),

            // MCP Tools
            Target(
                relativePath: ".cache/chrome-devtools-mcp",
                toolName: "Chrome DevTools MCP",
                subcategory: "Browser Profile & Cache",
                description: "Temporary browser user data and GPU caches used during web inspection sessions."
            ),

            // Local Models & Weights
            Target(
                relativePath: ".ollama/models/blobs",
                toolName: "Ollama",
                subcategory: "Model Blobs",
                description: "Downloaded layer blobs and model weights for local Ollama execution."
            ),
            Target(
                relativePath: ".cache/lm-studio/models",
                toolName: "LM Studio",
                subcategory: "GGUF Model Weights",
                description: "Locally downloaded GGUF large language model weights in LM Studio storage."
            ),
            Target(
                relativePath: ".cache/huggingface/hub",
                toolName: "Hugging Face",
                subcategory: "Downloaded Model Hub",
                description: "Cached model checkpoints, tokenizers, and weights downloaded from Hugging Face."
            ),
            Target(
                relativePath: ".cache/torch",
                toolName: "PyTorch",
                subcategory: "Kernel & Model Caches",
                description: "Compiled PyTorch kernels and pretrained model cache."
            )
        ]

        for target in targets {
            let targetURL = home.appendingPathComponent(target.relativePath)
            onProgress(ScanProgress(
                currentCategory: .aiClutter,
                currentPath: targetURL.path,
                itemsFound: items.count,
                bytesFound: totalBytes
            ))

            var isDir: ObjCBool = false
            if FileManager.default.fileExists(atPath: targetURL.path, isDirectory: &isDir) {
                let size = FileUtilities.calculateSize(at: targetURL)
                guard size > 0 else { continue }

                let values = try? targetURL.resourceValues(forKeys: [.contentModificationDateKey])

                let item = JunkItem(
                    url: targetURL,
                    displayName: "\(target.toolName) \(target.subcategory)",
                    subtitle: target.relativePath,
                    size: size,
                    category: .aiClutter,
                    subcategory: target.toolName,
                    isDirectory: isDir.boolValue,
                    lastModified: values?.contentModificationDate,
                    explanation: target.description,
                    isSelected: true
                )

                items.append(item)
                totalBytes += size
            }
        }

        return items
    }
}
